#!/usr/bin/env python3
"""Generate idempotent SQL for registration.sponsor from an ops spreadsheet CSV.

Keep normalize() aligned with br.voy.infrastructure.sponsor.SponsorKeyNormalizer:
trim, collapse whitespace, lowercase. Accents are preserved.

CSV header:
    name,city,approved,subscription_active,ranking,google_place_id,notes

Usage:
    python3 scripts/import-sponsors.py sponsors.csv > sponsors.sql
"""

import csv
import sys

TRUE_VALUES = {"1", "t", "true", "y", "yes", "s", "sim"}
FALSE_VALUES = {"0", "f", "false", "n", "no", "nao", "não"}


def normalize(value):
    if value is None:
        return ""
    collapsed = " ".join(str(value).split())
    return collapsed.lower()


def sql_text(value):
    if value is None or str(value).strip() == "":
        return "NULL"
    return "'" + str(value).replace("'", "''") + "'"


def sql_bool(value, row_number, column):
    token = str(value).strip().lower()
    if token in TRUE_VALUES:
        return "TRUE"
    if token in FALSE_VALUES:
        return "FALSE"
    raise SystemExit(f"row {row_number}: {column} must be true or false, got {value!r}")


def sql_int(value, row_number, column):
    token = str(value).strip()
    if token == "":
        return "NULL"
    if not token.isdigit():
        raise SystemExit(f"row {row_number}: {column} must be an integer, got {value!r}")
    return token


def main():
    if len(sys.argv) != 2:
        raise SystemExit("usage: python3 scripts/import-sponsors.py <sponsors.csv>")

    with open(sys.argv[1], newline="", encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))

    required = {"name", "city", "approved", "subscription_active"}
    if not rows and required:
        raise SystemExit("csv is empty or missing a header")
    missing = required.difference(rows[0].keys() if rows else required)
    if not rows:
        raise SystemExit("csv has a header but no sponsor rows")
    if missing:
        raise SystemExit("csv missing columns: " + ", ".join(sorted(missing)))

    print("-- generated by scripts/import-sponsors.py")
    print("BEGIN;")
    for index, row in enumerate(rows, start=2):
        name = (row.get("name") or "").strip()
        city = (row.get("city") or "").strip()
        if name == "" or city == "":
            raise SystemExit(f"row {index}: name and city are required")
        name_key = normalize(name)
        city_key = normalize(city)
        approved = sql_bool(row.get("approved"), index, "approved")
        subscription_active = sql_bool(
            row.get("subscription_active"), index, "subscription_active"
        )
        ranking = sql_int(row.get("ranking") or "", index, "ranking")
        google_place_id = sql_text(row.get("google_place_id"))
        notes = sql_text(row.get("notes"))
        print(
            "INSERT INTO registration.sponsor "
            "(name, city, name_key, city_key, approved, subscription_active, "
            "ranking, google_place_id, notes) VALUES ("
            f"{sql_text(name)}, {sql_text(city)}, {sql_text(name_key)}, {sql_text(city_key)}, "
            f"{approved}, {subscription_active}, {ranking}, {google_place_id}, {notes}) "
            "ON CONFLICT ON CONSTRAINT uk_sponsor_name_city DO UPDATE SET "
            "name = EXCLUDED.name, "
            "city = EXCLUDED.city, "
            "approved = EXCLUDED.approved, "
            "subscription_active = EXCLUDED.subscription_active, "
            "ranking = EXCLUDED.ranking, "
            "google_place_id = EXCLUDED.google_place_id, "
            "notes = EXCLUDED.notes, "
            "updated_at = CURRENT_TIMESTAMP;"
        )
    print("COMMIT;")


if __name__ == "__main__":
    main()
